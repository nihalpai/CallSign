"""
GEO agent example — wired to CallSign's approval gate.

What this mimics
----------------
The user's real GEO agent (in their separate don-drapor project) uses Lyzr Studio
to regenerate the site's LLMs.txt file.  That operation:

  1. Spends Lyzr Studio credits (~3,500 tokens).
  2. Overwrites the public-facing public/llms.txt on don-drapor.
  3. Publishes the new content immediately.

Because those side-effects are real and not easily reversible, the agent should ask
a human before proceeding.  This script shows exactly how: call CallSign's approval
gate, block until a human clicks Approve or Deny in Slack / the dashboard, then
generate (or skip) accordingly.

Running
-------
    export APPROVAL_API_KEY=<your key>
    export CALLSIGN_BASE_URL=http://localhost:8000   # default
    python examples/geo_agent.py

The script requires a running CallSign backend.  If the backend is down it prints a
clear error and exits non-zero.
"""

from __future__ import annotations

import os
import sys
import textwrap
from pathlib import Path

# ---------------------------------------------------------------------------
# Make `callsign` importable when running from the repo root without installing.
# ---------------------------------------------------------------------------
_sdk_path = Path(__file__).resolve().parent.parent / "sdk"
if _sdk_path.exists() and str(_sdk_path) not in sys.path:
    sys.path.insert(0, str(_sdk_path))

from callsign import CallSignError, approve  # noqa: E402

# ---------------------------------------------------------------------------
# Config (from environment)
# ---------------------------------------------------------------------------
CALLSIGN_BASE_URL = os.environ.get("CALLSIGN_BASE_URL", "http://localhost:8000")
APPROVAL_API_KEY = os.environ.get("APPROVAL_API_KEY", "")

OUTPUT_FILE = Path(__file__).parent / "output" / "LLMs.txt"

SAMPLE_LLMS_TXT = textwrap.dedent("""\
    # LLMs.txt — don-drapor
    # Auto-generated by the GEO agent via Lyzr Studio.
    # This file tells LLMs how to interpret and summarize this site.

    > Don Drapor is a creative technology studio focused on AI-first products.

    ## Pages
    - / : Home — Studio overview and featured projects
    - /work : Case studies and past client work
    - /about : Team, mission, and values
    - /contact : Get in touch

    ## Tone
    Professional but approachable.  The studio values clarity over cleverness.

    ## Do not summarize or index
    - /admin
    - /api
""")


def _gate_approval() -> bool:
    """
    Ask CallSign for human approval before running the GEO generation.
    Returns True if approved, False if denied or timed out.
    Raises SystemExit on connection / auth errors.
    """
    if not APPROVAL_API_KEY:
        print(
            "ERROR: APPROVAL_API_KEY is not set.  "
            "Export it before running: export APPROVAL_API_KEY=<your key>",
            file=sys.stderr,
        )
        sys.exit(1)

    print("Requesting approval from CallSign …")
    print(f"  backend: {CALLSIGN_BASE_URL}")
    print()

    try:
        decision = approve(
            "Generate LLMs.txt (GEO agent)",
            api_key=APPROVAL_API_KEY,
            base_url=CALLSIGN_BASE_URL,
            context="Prompted to regenerate the site's LLMs.txt for don-drapor",
            estimated_tokens=3500,
            dangers=[
                "Spends ~3,500 Lyzr credits",
                "Overwrites the existing public/llms.txt",
                "Content is published publicly",
            ],
            mode="callback",
            timeout=300,
            requester={"source": "agent", "name": "geo-agent"},
        )
    except CallSignError as exc:
        print(f"ERROR: CallSign API error — {exc}", file=sys.stderr)
        sys.exit(1)
    except Exception as exc:  # network down, refused, etc.
        print(
            f"ERROR: Could not reach CallSign at {CALLSIGN_BASE_URL} — {exc}\n"
            "Is the backend running?  cd backend && uvicorn app.main:app --reload",
            file=sys.stderr,
        )
        sys.exit(1)

    return bool(decision)


def _generate() -> None:
    """Write the sample LLMs.txt to examples/output/LLMs.txt."""
    OUTPUT_FILE.parent.mkdir(parents=True, exist_ok=True)
    OUTPUT_FILE.write_text(SAMPLE_LLMS_TXT, encoding="utf-8")


def main() -> None:
    approved = _gate_approval()

    if approved:
        _generate()
        print("approved — generated LLMs.txt (would have spent credits)")
        print(f"  written to: {OUTPUT_FILE}")
    else:
        print("denied — skipped generation, saved the credits")


if __name__ == "__main__":
    main()
